import test from 'node:test';
import assert from 'node:assert/strict';
import { forbiddenPublicPath, inspectPublicText } from '../scripts/public-hygiene.mjs';

test('public product documentation can discuss AI and example configuration', () => {
  const text = 'ThreadShelf Enhanced supports ChatGPT exports, OpenAI-compatible APIs, and local AI.\nSet OPENROUTER_API_KEY in the environment. Use https://example.org as an example URL.';
  assert.deepEqual(inspectPublicText(text), []);
  assert.equal(forbiddenPublicPath('public/examples/demo-conversation.json'), false);
  assert.equal(forbiddenPublicPath('content/privacy-security.md'), false);
});

test('common credential shapes are reported without returning their values', () => {
  const secrets = [
    'github' + '_pat_' + 'x'.repeat(72),
    'gh' + 'p_' + 'x'.repeat(36),
    'sk-' + 'proj-' + 'x'.repeat(60),
    'AK' + 'IA' + 'A'.repeat(16),
    ['-----BEGIN', 'PRIVATE KEY-----'].join(' ')
  ];
  for (const secret of secrets) {
    const findings = inspectPublicText(`Example\n${secret}`);
    assert.equal(findings.length, 1);
    assert.equal(findings[0].line, 2);
    assert.ok(!JSON.stringify(findings).includes(secret));
  }
});

test('private paths and internal authoring metadata are rejected', () => {
  const examples = [
    '/' + 'workspace/scratch/' + 'example/file.txt',
    ['Message Type:', 'FINAL_ANSWER'].join(' '),
    ['Generated by', 'ChatGPT'].join(' ')
  ];
  for (const example of examples) assert.ok(inspectPublicText(example).length > 0);
});

test('credential files, archives, local databases, and execution logs stay out of source', () => {
  for (const path of ['.env', '.env.local', 'config/credentials.json', 'id_ed25519', 'certificates/private.pem', 'archive.db', 'archive.sqlite3', 'export.zip', 'debug.log', '.codex/session.json']) {
    assert.equal(forbiddenPublicPath(path), true, path);
  }
  for (const path of ['.github/workflows/ci.yml', 'licenses/react-LICENSE.txt', 'SOURCE-REFERENCE.json']) {
    assert.equal(forbiddenPublicPath(path), false, path);
  }
});
